//PROGRAMA QUE CONVERTE CELSIUS PARA FAHREINHEIT
Console.WriteLine("Coloque quantos graus celsius você quer converter");
double celsius = Console.ReadLine();
double fahreiheit = (celsius * 9 / 5) + 32;
Console.WriteLine($"Certo, aqui está, {celsius} graus celsius é igual à {fahreiheit} graus fahreiheit ");